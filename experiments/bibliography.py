#!/usr/bin/env python3
"""bibliography.py - collect every paper the ontology cites into one reference list.

Sources, in order of title authority:
  - experiments/catalogue-papers.json   (per-mode papers, by catalogue number)
  - experiments/shipped-check-papers.json (per shipped check)
  - inline [arXiv:id] tags inside each mode's worked examples

Emits:
  - references/bibliography.md            (markdown table, committed)
  - docs/experiments/bibliography.html    (styled page, linked from the site)

Titles are never invented: a paper cited only inline, with no title in the JSON
sources, is listed with its id and marked 'title to verify'. Run after grounding
new examples so the reference list stays current.

Usage: experiments/bibliography.py
"""

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
EXP = ROOT / "experiments"
ONTOLOGY = ROOT / "ontology" / "ethical-ai.yaml"
MD_OUT = ROOT / "references" / "bibliography.md"
HTML_OUT = ROOT / "docs" / "experiments" / "bibliography.html"


def base(pid):
    h = pid.split("v")[0]
    return h if h.replace(".", "").isdigit() else pid


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def collect():
    o = yaml.safe_load(ONTOLOGY.read_text(encoding="utf-8"))
    modes = o["modes"]
    cat = {int(k): v for k, v in
           json.loads((EXP / "catalogue-papers.json").read_text()).items()}
    ship = json.loads((EXP / "shipped-check-papers.json").read_text())

    title, year, cited_by = {}, {}, {}

    def note(pid, modename, t="", y=""):
        pid = base(pid)
        if t and not title.get(pid):
            title[pid] = t
        if y and not year.get(pid):
            year[pid] = y
        cited_by.setdefault(pid, set())
        if modename:
            cited_by[pid].add(modename)

    num_to_name = {m.get("num"): m["name"] for m in modes}
    for num, entry in cat.items():
        for p in entry.get("papers", []):
            note(p["id"], num_to_name.get(num), p.get("title", ""), p.get("year", ""))

    name_by_slug = {slug(m["name"]): m["name"] for m in modes}
    for cid, entry in ship.items():
        for p in entry.get("papers", []):
            note(p["id"], name_by_slug.get(cid), p.get("title", ""), p.get("year", ""))

    # inline [arXiv:id] tags on worked examples: these are the papers actually read
    for m in modes:
        for e in (m.get("examples") or []):
            for pid in re.findall(r"arXiv:(\d{4}\.\d{4,5})", e):
                note(pid, m["name"])

    rows = []
    for pid in sorted(cited_by):
        rows.append({
            "id": pid,
            "title": title.get(pid, ""),
            "year": year.get(pid, ""),
            "modes": sorted(cited_by[pid]),
        })
    return rows


def write_md(rows):
    titled = sum(1 for r in rows if r["title"])
    lines = [
        "# Bibliography",
        "",
        f"Every paper cited across the ontology: {len(rows)} distinct works, "
        f"{titled} with a recorded title. Generated by "
        "`experiments/bibliography.py`; do not edit by hand.",
        "",
        "Papers cited only inline in a worked example, with no title in the JSON "
        "sources, are marked *title to verify* rather than given an invented title.",
        "",
        "| arXiv | Title | Year | Cited by |",
        "|---|---|---|---|",
    ]
    for r in rows:
        t = r["title"] or "*title to verify*"
        modes = ", ".join(r["modes"][:4]) + (" ..." if len(r["modes"]) > 4 else "")
        lines.append(f"| [{r['id']}](https://arxiv.org/abs/{r['id']}) | {t} | "
                     f"{r['year']} | {modes} |")
    MD_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def write_html(rows):
    titled = sum(1 for r in rows if r["title"])
    trs = []
    for r in rows:
        t = esc(r["title"]) if r["title"] else '<em class="tv">title to verify</em>'
        modes = esc(", ".join(r["modes"]))
        trs.append(
            f'<tr><td><a href="https://arxiv.org/abs/{r["id"]}" target="_blank" '
            f'rel="noopener">{r["id"]}</a></td><td>{t}</td><td>{esc(r["year"])}</td>'
            f'<td class="m">{modes}</td></tr>')
    html = f"""<!doctype html>
<html lang="en"><head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Bibliography · EthicalAI</title>
<link rel="icon" type="image/png" href="../favicon.png">
<style>
:root{{--accent:#FF4931;--accent-d:#c2341a;--ink:#141414;--muted:#64646a;--line:#e7e5e2;--panel:#f6f5f4}}
*{{box-sizing:border-box}}
body{{margin:0;font-family:Manrope,system-ui,sans-serif;color:var(--ink);line-height:1.55;background:#fff}}
.wrap{{max-width:1080px;margin:0 auto;padding:40px 22px 80px}}
a{{color:var(--accent-d)}}
h1{{font-size:clamp(24px,4vw,34px);margin:0 0 6px}}
.eyebrow{{font-size:12.5px;letter-spacing:.14em;text-transform:uppercase;color:var(--accent);font-weight:700;margin:0 0 12px}}
.lede{{font-size:17px;color:#333;max-width:70ch}}
.back{{font-size:13px;display:inline-block;margin-bottom:18px}}
.tablewrap{{overflow-x:auto;margin-top:18px}}
table{{border-collapse:collapse;width:100%;font-size:13.5px}}
th,td{{border:1px solid var(--line);padding:7px 10px;text-align:left;vertical-align:top}}
th{{background:var(--panel);font-weight:700;position:sticky;top:0}}
td.m{{color:var(--muted);font-size:12.5px}}
.tv{{color:#b08400}}
code{{background:var(--panel);padding:1px 5px;border-radius:4px}}
</style></head>
<body><div class="wrap">
<a class="back" href="../index.html#paper">&larr; EthicalAI</a>
<p class="eyebrow">Reference list</p>
<h1>Bibliography</h1>
<p class="lede">Every paper cited across the ontology: {len(rows)} distinct works,
{titled} with a recorded title. Papers cited only inline in a worked example, with
no title in the source data, are marked <em class="tv">title to verify</em> rather
than given an invented one. Generated by <code>experiments/bibliography.py</code>.</p>
<div class="tablewrap">
<table>
<thead><tr><th>arXiv</th><th>Title</th><th>Year</th><th>Cited by</th></tr></thead>
<tbody>
{chr(10).join(trs)}
</tbody>
</table>
</div>
</div></body></html>
"""
    HTML_OUT.write_text(html, encoding="utf-8")


def main():
    rows = collect()
    write_md(rows)
    write_html(rows)
    titled = sum(1 for r in rows if r["title"])
    print(f"bibliography: {len(rows)} papers ({titled} titled) -> "
          f"{MD_OUT.relative_to(ROOT)}, {HTML_OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
